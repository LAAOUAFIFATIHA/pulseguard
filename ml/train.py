"""Train a very small classifier on PulseGuard sessions and export it to C.

Reads every *.json in ml/data/ (simulated sessions or files from the app's
Export button). Needs only NumPy.

    python ml/train.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
FEATURES = ["hr_bpm", "rr_cv", "ecg_std_mv", "accel_std_g"]
HIDDEN = 12


def r_peaks(samples, fs, threshold=0.5, refractory=0.25):
    """Same rule as BeatDetector in src/anomaly.js (easy to port to C)."""
    peaks, in_peak, best_v, best_t, last = [], False, 0.0, 0.0, -1e9
    for i, v in enumerate(samples):
        t = i / fs
        if not in_peak:
            if v > threshold and t - last > refractory:
                in_peak, best_v, best_t = True, v, t
        elif v > best_v:
            best_v, best_t = v, t
        elif v < threshold:
            in_peak, last = False, best_t
            peaks.append(best_t)
    return peaks


def features(chunk):
    ecg = np.asarray(chunk["samples"], dtype=float)
    rr = np.diff(r_peaks(ecg, chunk["sampleRate"]))
    hr = 60.0 / rr.mean() if len(rr) else 0.0
    cv = rr.std() / rr.mean() if len(rr) > 1 else 0.0
    accel = np.asarray(chunk.get("accel") or [1.0], dtype=float)
    return [hr, cv, ecg.std(), accel.std()]


def load(folder):
    x, y, groups = [], [], []
    for path in sorted(folder.glob("*.json")):
        session = json.loads(path.read_text(encoding="utf-8"))
        for chunk in session["chunks"]:
            if chunk["sampleCount"] < 10 * chunk["sampleRate"]:
                continue  # keep complete 10 s blocks only
            x.append(features(chunk))
            y.append(chunk["label"])
            groups.append(session["sessionId"])
    return np.array(x), np.array(y), np.array(groups)


def forward(p, x):
    h = np.maximum(0, x @ p["w1"] + p["b1"])
    z = h @ p["w2"] + p["b2"]
    z -= z.max(axis=1, keepdims=True)
    prob = np.exp(z) / np.exp(z).sum(axis=1, keepdims=True)
    return h, prob


def train(x, y, n_classes, epochs=2000, lr=0.05, seed=0):
    rng = np.random.default_rng(seed)
    p = {
        "w1": rng.normal(0, 0.5, (x.shape[1], HIDDEN)),
        "b1": np.zeros(HIDDEN),
        "w2": rng.normal(0, 0.5, (HIDDEN, n_classes)),
        "b2": np.zeros(n_classes),
    }
    target = np.eye(n_classes)[y]
    m = {k: np.zeros_like(v) for k, v in p.items()}
    v = {k: np.zeros_like(val) for k, val in p.items()}
    for step in range(1, epochs + 1):  # full-batch gradient descent with Adam
        h, prob = forward(p, x)
        d2 = (prob - target) / len(x)
        d1 = (d2 @ p["w2"].T) * (h > 0)
        grads = {"w1": x.T @ d1, "b1": d1.sum(0), "w2": h.T @ d2, "b2": d2.sum(0)}
        for k, g in grads.items():
            m[k] = 0.9 * m[k] + 0.1 * g
            v[k] = 0.999 * v[k] + 0.001 * g * g
            p[k] -= lr * (m[k] / (1 - 0.9**step)) / (np.sqrt(v[k] / (1 - 0.999**step)) + 1e-8)
    return p


def c_array(name, values):
    flat = ", ".join(f"{float(v):.7g}f" for v in np.ravel(values))
    return f"static const float {name}[{np.size(values)}] = {{{flat}}};\n"


def export_c(path, p, mean, std, classes):
    n_in, n_out = len(FEATURES), len(classes)
    labels = ", ".join(f'"{c}"' for c in classes)
    code = f"""// Generated by ml/train.py. Do not edit.
// Features, in order: {", ".join(FEATURES)} (computed over 10 s)
#pragma once

#define PG_FEATURES {n_in}
#define PG_CLASSES {n_out}
static const char *const PG_LABELS[PG_CLASSES] = {{{labels}}};

"""
    code += c_array("PG_MEAN", mean) + c_array("PG_STD", std)
    code += c_array("PG_W1", p["w1"]) + c_array("PG_B1", p["b1"])
    code += c_array("PG_W2", p["w2"]) + c_array("PG_B2", p["b2"])
    code += f"""
// Returns the index of the most likely class in PG_LABELS.
static inline int pulseguard_predict(const float x[PG_FEATURES]) {{
  float h[{HIDDEN}];
  for (int j = 0; j < {HIDDEN}; j++) {{
    float s = PG_B1[j];
    for (int i = 0; i < PG_FEATURES; i++) s += (x[i] - PG_MEAN[i]) / PG_STD[i] * PG_W1[i * {HIDDEN} + j];
    h[j] = s > 0 ? s : 0;
  }}
  int best = 0;
  float bestScore = 0;
  for (int k = 0; k < PG_CLASSES; k++) {{
    float s = PG_B2[k];
    for (int j = 0; j < {HIDDEN}; j++) s += h[j] * PG_W2[j * PG_CLASSES + k];
    if (k == 0 || s > bestScore) {{ best = k; bestScore = s; }}
  }}
  return best;
}}
"""
    path.parent.mkdir(exist_ok=True)
    path.write_text(code, encoding="utf-8")


def main():
    x, labels, groups = load(HERE / "data")
    if len(x) == 0:
        raise SystemExit("No data. Run: node ml/generate_dataset.mjs")
    classes = sorted(set(labels))
    y = np.array([classes.index(label) for label in labels])

    # Split by SESSION, so blocks of one recording are never in both sets.
    rng = np.random.default_rng(1)
    test_ids = []
    for c in classes:
        ids = np.unique(groups[labels == c])
        rng.shuffle(ids)
        test_ids += list(ids[: max(1, int(0.3 * len(ids)))])
    test = np.isin(groups, test_ids)

    mean, std = x[~test].mean(0), x[~test].std(0) + 1e-6
    p = train((x[~test] - mean) / std, y[~test], len(classes))
    pred = forward(p, (x[test] - mean) / std)[1].argmax(1)

    print(f"Blocks: {(~test).sum()} train, {test.sum()} test")
    print(f"Test accuracy: {100 * (pred == y[test]).mean():.1f} %\n")
    print("Confusion matrix (rows = truth, columns = prediction)")
    print(" " * 14 + " ".join(f"{c[:8]:>8}" for c in classes))
    for i, c in enumerate(classes):
        row = [int(((y[test] == i) & (pred == j)).sum()) for j in range(len(classes))]
        print(f"{c:<14}" + " ".join(f"{n:>8}" for n in row))

    out = HERE / "out" / "pulseguard_model.h"
    export_c(out, p, mean, std, classes)
    size = sum(v.size for v in p.values()) * 4
    print(f"\nExported {out.relative_to(HERE.parent)} ({size} bytes of weights)")


if __name__ == "__main__":
    main()
